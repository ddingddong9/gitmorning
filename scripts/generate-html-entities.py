"""Generate Sources/GitMorningCore/HTMLEntities.swift from Python's HTML5 entity table.

The Swift Trending parser and the Python collector must decode the same named
entities. Python's html.entities.html5 is the reference, so the Swift table is
generated from it rather than maintained by hand.

    python3 scripts/generate-html-entities.py
"""
import html.entities
from pathlib import Path

OUTPUT = Path(__file__).resolve().parent.parent / "Sources/GitMorningCore/HTMLEntities.swift"


def main():
    # Only the semicolon-terminated forms; GitHub always terminates entities.
    entries = sorted((name[:-1], value) for name, value in html.entities.html5.items() if name.endswith(";"))
    encoded = [name + "=" + "-".join(format(ord(c), "x") for c in value) for name, value in entries]
    lines = [" ".join(encoded[i:i + 12]) for i in range(0, len(encoded), 12)]
    body = "\n".join(lines)
    OUTPUT.write_text(
        "// Generated by scripts/generate-html-entities.py from Python's html.entities.html5.\n"
        "// Do not edit by hand.\n\n"
        "enum HTMLEntities {\n"
        "    static let named: [String: String] = {\n"
        "        var table: [String: String] = [:]\n"
        "        for entry in raw.split(whereSeparator: { $0 == \" \" || $0 == \"\\n\" }) {\n"
        "            let parts = entry.split(separator: \"=\", maxSplits: 1)\n"
        "            let scalars = parts[1].split(separator: \"-\").compactMap { UInt32($0, radix: 16).flatMap(Unicode.Scalar.init) }\n"
        "            table[String(parts[0])] = String(String.UnicodeScalarView(scalars))\n"
        "        }\n"
        "        return table\n"
        "    }()\n\n"
        "    private static let raw = \"\"\"\n" + body + "\n\"\"\"\n"
        "}\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(entries)} entities to {OUTPUT}")


if __name__ == "__main__":
    main()
